function crc32(buffer) {
  let crc = -1;
  for (let i = 0; i < buffer.length; i += 1) {
    crc ^= buffer[i];
    for (let bit = 0; bit < 8; bit += 1) crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
  }
  return (crc ^ -1) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const typeBuffer = Buffer.from(type, 'ascii');
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([typeBuffer, data])), 0);
  return Buffer.concat([length, typeBuffer, data, crc]);
}

/** 把文本渲染成黑底白字的 PNG */
function renderText(lines, options = {}) {
  const scale = options.scale || 3;
  const pad = 16;
  const lineHeight = 9 * scale;
  const charWidth = 6 * scale;
  const width = pad * 2 + Math.max(...lines.map((l) => l.length)) * charWidth;
  const height = pad * 2 + lines.length * lineHeight;

  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y += 1) {
    const rowStart = y * (width * 4 + 1);
    raw[rowStart] = 0;
    for (let x = 0; x < width; x += 1) {
      const offset = rowStart + 1 + x * 4;
      raw[offset] = 12;
      raw[offset + 1] = 16;
      raw[offset + 2] = 22;
      raw[offset + 3] = 255;
    }
  }

  lines.forEach((text, lineIndex) => {
    const baseY = pad + lineIndex * lineHeight;
    for (let i = 0; i < text.length; i += 1) {
      const glyph = FONT[text[i]] || FONT[' '];
      for (let gy = 0; gy < 7; gy += 1) {
        for (let gx = 0; gx < 5; gx += 1) {
          if (glyph[gy][gx] !== '1') continue;
          for (let sy = 0; sy < scale; sy += 1) {
            for (let sx = 0; sx < scale; sx += 1) {
              const px = pad + i * charWidth + gx * scale + sx;
              const py = baseY + gy * scale + sy;
              if (px >= width || py >= height) continue;
              const offset = py * (width * 4 + 1) + 1 + px * 4;
              raw[offset] = 235;
              raw[offset + 1] = 240;
              raw[offset + 2] = 245;
              raw[offset + 3] = 255;
            }
          }
        }
      }
    }
  });

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

function main() {
  const expected = [
    'PS C:\\Users\\user> Test-NetConnection 64.176.34.176 -Port 443',
    'TcpTestSucceeded : False',
    'Port 22 : OK',
  ];
  const png = renderText(expected);
  const file = path.join(__dirname, '..', 'data', 'ocr-selftest.png');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, png);
  console.log(`已生成测试图: ${file} (${png.length} 字节)\n`);

  const lines = recognize(file, 'en-GB');
  console.log('OCR 识别结果:');
  lines.forEach((l) => console.log('  ' + l));

  const joined = lines.join(' ').toLowerCase();
  const hits = ['tcp', 'false', 'port', '22'].filter((token) => joined.includes(token));
  console.log(`\n命中关键字: ${hits.join(', ') || '(无)'}`);
  console.log(hits.length >= 3 ? '✅ 本地离线 OCR 可用' : '⚠️ 识别效果一般，复杂截图建议改贴文字');
}

if (require.main === module) main();
